def _build_trace_bundle(
    design_root: Path, rows: list[dict[str, str]]
) -> dict[str, Any]:
    by_id = {row["movement_id"]: row for row in rows}
    declared_losses: list[dict[str, Any]] = []
    for movement_id in DECLARED_LOSS_IDS:
        row = by_id[movement_id]
        detail = _LOSS_DETAIL[movement_id]
        declared_losses.append(
            {
                "movement_id": movement_id,
                "fields": detail["fields"],
                "scope": detail["scope"],
                "account": row["projection_loss"],
            }
        )
    legacy_traces: list[dict[str, Any]] = []
    for trace_id, movement_refs in LEGACY_TRACES:
        test_refs: list[dict[str, Any]] = []
        for movement_id in movement_refs:
            for ref in _split_refs(by_id[movement_id]["acceptance_trace"]):
                if _looks_like_repo_path(ref):
                    test_refs.append(_resolve_test_ref(design_root, ref))
        legacy_traces.append(
            {
                "trace_id": trace_id,
                "movement_refs": list(movement_refs),
                "target_status": "REVIEW_CANDIDATE",
                "test_refs": test_refs,
            }
        )
    bundle: dict[str, Any] = {
        "schema": "mrw.functorial_successor.c7_trace_and_loss_bundle.v1",
        "family": "C7",
        "status": STATUS,
        "legacy_traces": legacy_traces,
        "declared_losses": declared_losses,
        "zero_loss_declared": False,
        "unaccepted_loss_blockers": [],
        "content_digest": "",
    }
    bundle["content_digest"] = _content_digest(bundle)
    return bundle


