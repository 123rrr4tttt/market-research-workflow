def _atomic_write(path: Path, data: bytes) -> None:
    if path.exists() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
        path.chmod(0o644)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def main(argv: list[str] | None = None) -> int:
    script_root = Path(__file__).resolve().parents[3]
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", type=Path, default=script_root)
    parser.add_argument(
        "--design-root",
        type=Path,
        default=Path(
            os.environ.get("C7_SEMANTIC_MOVEMENT_DESIGN_ROOT", str(script_root))
        ),
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    repo_root = args.repo_root.resolve()
    design_root = args.design_root.resolve()
    try:
        documents = build_documents(design_root)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"INVALID: {exc}")
        return 2
    if args.check:
        drift = [
            relative.as_posix()
            for relative, expected in documents.items()
            if not (repo_root / relative).exists()
            or (repo_root / relative).read_bytes() != expected
        ]
        if drift:
            print(json.dumps({"status": "DRIFT", "paths": drift}, sort_keys=True))
            return 1
        print(
            json.dumps({"status": "CHECK_OK", "unassigned_blockers": 0}, sort_keys=True)
        )
        return 0
    for relative, expected in documents.items():
        _atomic_write(repo_root / relative, expected)
    print(json.dumps({"status": "WROTE", "unassigned_blockers": 0}, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
