def _digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _canonical(value: Any) -> bytes:
    return (
        json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
        + "\n"
    ).encode("utf-8")


def _content_digest(value: dict[str, Any]) -> str:
    payload = {key: item for key, item in value.items() if key != "content_digest"}
    return _digest(_canonical(payload))


def _clean(cell: str) -> str:
    return cell.strip().strip("`")


def parse_design(design_text: str) -> list[dict[str, str]]:
    """Parse the frozen C7 v3 design table into its 20 fixed rows."""

    rows: list[dict[str, str]] = []
    labels = ("movement_id",) + REQUIRED_FIELDS + ("disposition",)
    for line in design_text.splitlines():
        if not line.startswith("| C7-MOV-"):
            continue
        cells = [_clean(cell) for cell in line.strip().strip("|").split("|")]
        if len(cells) != len(labels):
            raise ValueError(
                f"movement row has {len(cells)} cells, expected {len(labels)}"
            )
        row = dict(zip(labels, cells, strict=True))
        if not all(row[field] for field in labels):
            raise ValueError(
                f"movement row contains an empty field: {row['movement_id']}"
            )
        if row["disposition"] not in ALLOWED_DISPOSITIONS:
            raise ValueError(f"illegal disposition: {row['disposition']}")
        rows.append(row)
    if len(rows) != 20 or len({row["movement_id"] for row in rows}) != 20:
        raise ValueError("C7 v3 design must contain 20 unique movement rows")
    actual_blockers = tuple(
        row["movement_id"] for row in rows if row["disposition"] == "UNASSIGNED_BLOCKER"
    )
    if actual_blockers != BLOCKER_IDS:
        raise ValueError("C7 blocker identity/order drift")
    return rows


def _binding(design_root: Path, relative: Path, role: str) -> dict[str, Any]:
    data = (design_root / relative).read_bytes()
    return {
        "path": relative.as_posix(),
        "role": role,
        "sha256": _digest(data),
        "bytes": len(data),
        "lines": len(data.splitlines()),
    }


def _split_refs(value: str) -> list[str]:
    return [ref.strip() for ref in value.split(";") if ref.strip()]


def _looks_like_repo_path(value: str) -> bool:
    return value.startswith(("main/", "development/"))


def _resolve_test_ref(design_root: Path, ref: str) -> dict[str, Any]:
    path_part, node_id = ref.split("::", 1)
    if not _looks_like_repo_path(path_part):
        raise ValueError(f"test ref is not a repo path: {ref!r}")
    full = design_root / path_part
    if not full.is_file():
        raise ValueError(f"test ref file missing: {ref!r}")
    data = full.read_bytes()
    text = data.decode("utf-8", errors="replace")
    if f"def {node_id}" not in text and f"class {node_id}" not in text:
        raise ValueError(f"test node {node_id!r} missing from {path_part!r}")
    return {
        "ref": ref,
        "path": path_part,
        "node_id": node_id,
        "sha256": _digest(data),
        "bytes": len(data),
        "lines": len(data.splitlines()),
    }


