def _evidence_ref_summary(matrix: dict[str, Any]) -> dict[str, Any]:
    total = 0
    resolved = 0
    absence = 0
    typed_absence = 0
    unresolved: list[dict[str, Any]] = []
    for row in matrix["movements"]:
        for field in ("source_evidence", "target_realization", "acceptance_trace"):
            for binding in row["evidence_bindings"].get(field, []):
                total += 1
                kind = binding["kind"]
                if kind == "resolved":
                    resolved += 1
                elif kind == "absence_evidence":
                    absence += 1
                elif kind == "typed_absence":
                    typed_absence += 1
                elif kind == "unresolved":
                    unresolved.append(binding)
    return {
        "total_refs": total,
        "resolved": resolved,
        "absence_evidence": absence,
        "typed_absence": typed_absence,
        "unresolved": unresolved,
    }


