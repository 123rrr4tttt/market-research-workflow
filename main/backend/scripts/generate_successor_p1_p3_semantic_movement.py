def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _canonical(value: Any) -> bytes:
    return (
        json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
        + "\n"
    ).encode("utf-8")


def _content_digest(value: dict[str, Any]) -> str:
    payload = {key: item for key, item in value.items() if key != "content_digest"}
    return _sha256(_canonical(payload))


def _binding(repo_root: Path, relative: Path, role: str) -> dict[str, Any]:
    data = (repo_root / relative).read_bytes()
    return {
        "path": relative.as_posix(),
        "role": role,
        "sha256": _sha256(data),
        "bytes": len(data),
        "lines": len(data.splitlines()),
    }


def _load_json(repo_root: Path, relative: Path) -> Any:
    return json.loads((repo_root / relative).read_text(encoding="utf-8"))


def _clean(cell: str) -> str:
    return cell.strip().strip("`")


def parse_c7_design(design_text: str) -> list[dict[str, str]]:
    """Parse the frozen C7 v2 design table into its 20 fixed rows."""

    rows: list[dict[str, str]] = []
    labels = ("movement_id",) + REQUIRED_FIELDS + ("disposition",)
    for line in design_text.splitlines():
        if not line.startswith("| C7-MOV-"):
            continue
        cells = [_clean(cell) for cell in line.strip().strip("|").split("|")]
        if len(cells) != len(labels):
            raise ValueError(
                f"movement row has {len(cells)} cells, expected {len(labels)}"
            )
        row = dict(zip(labels, cells, strict=True))
        if not all(row[field] for field in labels):
            raise ValueError(
                f"movement row contains an empty field: {row['movement_id']}"
            )
        if row["disposition"] not in ALLOWED_DISPOSITIONS:
            raise ValueError(f"illegal disposition: {row['disposition']}")
        rows.append(row)
    if len(rows) != 20 or len({row["movement_id"] for row in rows}) != 20:
        raise ValueError("C7 v2 design must contain 20 unique movement rows")
    blockers = tuple(
        row["movement_id"] for row in rows if row["disposition"] == "UNASSIGNED_BLOCKER"
    )
    if blockers != C7_BLOCKER_IDS:
        raise ValueError("C7 blocker identity/order drift")
    return rows


def _resolve_json_pointer(doc: Any, pointer: str) -> tuple[bool, str]:
    if not pointer.startswith("/"):
        return False, "not a JSON pointer"
    tokens = pointer.split("/")[1:]
    current: Any = doc
    for token in tokens:
        token = token.replace("~1", "/").replace("~0", "~")
        if isinstance(current, dict):
            if token not in current:
                return False, f"pointer token {token!r} missing"
            current = current[token]
        elif isinstance(current, list):
            try:
                index = int(token)
            except ValueError:
                return False, f"pointer token {token!r} is not a list index"
            if index < 0 or index >= len(current):
                return False, f"pointer index {index} out of range"
            current = current[index]
        else:
            return False, f"cannot descend through {type(current).__name__}"
    return True, ""


def _resolve_fragment_selector(doc: Any, pointer: str) -> tuple[bool, str]:
    """Resolve p1-fragment style selectors such as C1.1 or C1.1.payload_schema."""

    current: Any | None = None
    remainder = ""
    if isinstance(doc, list):
        for item in doc:
            if not isinstance(item, dict) or "cell" not in item:
                continue
            cell = str(item["cell"])
            if pointer == cell:
                current = item
                break
            if pointer.startswith(cell + "."):
                current = item
                remainder = pointer[len(cell) + 1 :]
                break
        if current is None:
            return False, f"cell selector {pointer!r} missing from fragment"
    elif isinstance(doc, dict):
        if pointer in doc:
            current = doc[pointer]
        else:
            matches = [
                key for key in doc if pointer == key or pointer.startswith(key + ".")
            ]
            if not matches:
                return False, f"selector {pointer!r} missing from fragment"
            key = matches[0]
            current = doc[key]
            remainder = pointer[len(key) + 1 :]
    else:
        return False, f"selector {pointer!r} cannot resolve non-container fragment"
    if not remainder:
        return True, ""
    for token in remainder.split("."):
        if not isinstance(current, dict) or token not in current:
            return False, f"selector key {token!r} missing"
        current = current[token]
    return True, ""


def _resolve_pointer(doc: Any, pointer: str) -> tuple[bool, str]:
    if pointer.startswith("/"):
        return _resolve_json_pointer(doc, pointer)
    return _resolve_fragment_selector(doc, pointer)


