"""Deterministically generate the P1-P3 retrospective semantic movement backfill.

The generator consumes the mainline P1-P3 semantic-movement spec and the
independent C7 external design artifacts, then projects them into:

- evidence/semantic-movement/fragments/C1.v1.json ... C9.v1.json
- evidence/semantic-movement/P1P3LegacyDonorSemanticMovementInventory.v1.json
- evidence/semantic-movement/P1P3SuccessorMovementMatrix.v1.json
- evidence/semantic-movement/P1P3SemanticMovementGate.v1.json

It is a mechanical serializer only.  It never changes movement taxonomy,
dispositions, authority or promotion decisions, and it never writes to the
mainline spec, the C7 design artifacts, P1-P3 evidence or implementation.

Run from ``main/backend``::

    python3.11 scripts/generate_successor_p1_p3_semantic_movement.py
    python3.11 scripts/generate_successor_p1_p3_semantic_movement.py --check

``--repo-root`` selects the canonical evidence root that owns the mainline spec
and C7 design inputs; ``--output-root`` (default: ``--repo-root``) selects where
the generated artifacts are written or checked.  During integration both roots
are the repository root; a frozen input checkout may be used as ``--repo-root``
while this checkout receives the generated artifacts via ``--output-root``.

Exit codes for ``--check``: 0 = artifacts match regenerated bytes, 1 = drift
detected without writing, 2 = invalid input or output root.
"""

