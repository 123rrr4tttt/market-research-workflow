def _computed_blocker_account(rows: list[dict[str, Any]]) -> dict[str, Any]:
    """Derive the blocker account from the actual projected movement rows."""

    inline_by_family: dict[str, int] = {}
    inline_count = 0
    for family in INLINE_FAMILIES:
        count = sum(
            row["family"] == family and row["disposition"] == "UNASSIGNED_BLOCKER"
            for row in rows
        )
        inline_by_family[family] = count
        inline_count += count
    external_c7_count = sum(
        row["family"] == "C7" and row["disposition"] == "UNASSIGNED_BLOCKER"
        for row in rows
    )
    exact = inline_count + external_c7_count
    calculation = (
        " + ".join(str(inline_by_family[family]) for family in INLINE_FAMILIES)
        + " + "
        + str(external_c7_count)
        + " = "
        + str(exact)
    )
    return {
        "inline_by_family": inline_by_family,
        "inline_count": inline_count,
        "external_C7_count": external_c7_count,
        "exact_count_for_this_spec": exact,
        "calculation": calculation,
        "count_status": "MAINLINE_FIXED_EXTERNAL_C7_BOUND",
        "promotion_allowed": False,
    }


