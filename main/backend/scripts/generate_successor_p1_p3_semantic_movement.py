def build_documents(repo_root: Path) -> dict[Path, bytes]:
    """Build every generated artifact keyed by repository-relative path."""

    repo_root = repo_root.resolve()
    spec = _load_json(repo_root, SPEC_REL)
    if spec.get("schema") != "mrw.functorial_successor.p1_p3_semantic_movement_spec.v1":
        raise ValueError("mainline spec schema mismatch")
    if len(spec["movements"]) != 40:
        raise ValueError("mainline spec must contain 40 inline movements")
    design_bytes = (repo_root / C7_DESIGN_REL).read_bytes()
    design_sha256 = _sha256(design_bytes)
    if design_sha256 != C7_DESIGN_SHA256:
        raise ValueError(
            f"C7 design SHA drift: expected {C7_DESIGN_SHA256}, got {design_sha256}"
        )
    design_rows = parse_c7_design(design_bytes.decode("utf-8"))
    c7_inventory = _load_json(repo_root, C7_INVENTORY_REL)
    c7_matrix = _load_json(repo_root, C7_MATRIX_REL)
    c7_trace = _load_json(repo_root, C7_TRACE_REL)
    if c7_inventory["content_digest"] != C7_INVENTORY_DIGEST:
        raise ValueError("C7 inventory digest drift")
    if c7_matrix["content_digest"] != C7_MATRIX_DIGEST:
        raise ValueError("C7 matrix digest drift")
    if c7_trace["content_digest"] != C7_TRACE_DIGEST:
        raise ValueError("C7 trace digest drift")

    inline_rows = _project_inline_rows(repo_root, spec)
    c7_rows, c7_binding = _project_c7_rows(
        repo_root, c7_matrix, design_rows, design_sha256
    )
    matrix = build_matrix(repo_root, spec, inline_rows, c7_rows, c7_binding)
    fragments = build_fragments(repo_root, matrix)
    inventory = build_inventory(matrix)
    gate = build_gate(matrix, inventory, spec)

    documents: dict[Path, bytes] = {}
    for family in FAMILIES:
        documents[FRAGMENT_REL / f"{family}.v1.json"] = _canonical(fragments[family])
    documents[INVENTORY_REL] = _canonical(inventory)
    documents[MATRIX_REL] = _canonical(matrix)
    documents[GATE_REL] = _canonical(gate)
    return documents


def _atomic_write(path: Path, data: bytes) -> None:
    if path.exists() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
        path.chmod(0o644)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--repo-root", type=Path, default=Path(__file__).resolve().parents[3]
    )
    parser.add_argument(
        "--output-root",
        type=Path,
        default=None,
        help="where generated artifacts are written or checked (default: --repo-root)",
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    repo_root = args.repo_root.resolve()
    output_root = (args.output_root or args.repo_root).resolve()
    try:
        documents = build_documents(repo_root)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"INVALID: {exc}")
        return 2
    matrix = json.loads(documents[MATRIX_REL])
    counts = {
        "inline_movements": matrix["inline_movement_count"],
        "external_c7_movements": matrix["external_c7_movement_count"],
        "total_movements": matrix["total_movement_count"],
        "exact_blockers": matrix["unassigned_blocker_count"],
    }
    if args.check:
        drift = [
            relative.as_posix()
            for relative, expected in documents.items()
            if not (output_root / relative).exists()
            or (output_root / relative).read_bytes() != expected
        ]
        if drift:
            print(
                json.dumps(
                    {"status": "DRIFT", "paths": drift, **counts},
                    sort_keys=True,
                )
            )
            return 1
        print(
            json.dumps(
                {
                    "status": "CHECK_OK",
                    **counts,
                },
                sort_keys=True,
            )
        )
        return 0
    for relative, expected in documents.items():
        _atomic_write(output_root / relative, expected)
    print(
        json.dumps(
            {
                "status": "WROTE",
                **counts,
            },
            sort_keys=True,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
