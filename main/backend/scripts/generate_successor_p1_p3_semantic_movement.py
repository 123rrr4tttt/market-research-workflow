def _looks_like_repo_path(value: str) -> bool:
    if value.startswith(_REPO_PATH_PREFIXES):
        return True
    return "/" in value and value.endswith(_KNOWN_SUFFIXES)


def resolve_ref(repo_root: Path, ref: str) -> dict[str, Any]:
    """Classify one source_evidence/target_realization/acceptance_trace ref."""

    if ref.startswith("MISSING::") or "REQUIRED_UNASSIGNED" in ref:
        return {"kind": "typed_absence", "ref": ref}
    path_part = ref.split("#", 1)[0]
    node_id: str | None = None
    if "::" in path_part:
        path_part, node_id = path_part.split("::", 1)
    if not _looks_like_repo_path(path_part):
        return {"kind": "absence_evidence", "ref": ref}
    full = repo_root / path_part
    if not full.is_file():
        return {
            "kind": "unresolved",
            "ref": ref,
            "path": path_part,
            "reason": "missing file in evidence root",
        }
    data = full.read_bytes()
    binding: dict[str, Any] = {
        "kind": "resolved",
        "ref": ref,
        "path": path_part,
        "sha256": _sha256(data),
        "bytes": len(data),
        "lines": len(data.splitlines()),
    }
    pointer = ref.split("#", 1)[1] if "#" in ref else None
    if node_id is not None:
        text = data.decode("utf-8", errors="replace")
        if f"def {node_id}" not in text and f"class {node_id}" not in text:
            return {
                "kind": "unresolved",
                "ref": ref,
                "path": path_part,
                "reason": "test node id not found in file",
            }
        binding["node_id"] = node_id
    if pointer is not None:
        if full.suffix == ".json":
            ok, why = _resolve_pointer(json.loads(data), pointer)
        else:
            ok, why = False, "pointer on non-JSON evidence file"
        if not ok:
            return {
                "kind": "unresolved",
                "ref": ref,
                "path": path_part,
                "reason": why,
            }
        binding["pointer"] = pointer
    return binding


def _expand_refs(value: Any) -> list[str]:
    """Split semicolon-joined evidence refs into individual exact refs.

    C7 v3 row cells join multiple repository paths or test node ids with
    ``"; "``.  A cell is split only when at least one token is repository-path
    shaped; design-owned free text stays one absence-evidence ref.
    """

    refs = value if isinstance(value, list) else [value]
    expanded: list[str] = []
    for ref in refs:
        ref = str(ref)
        if ";" not in ref:
            expanded.append(ref)
            continue
        tokens = [token.strip() for token in ref.split(";") if token.strip()]
        if any(
            _looks_like_repo_path(token.split("#")[0].split("::")[0])
            for token in tokens
        ):
            expanded.extend(tokens)
        else:
            expanded.append(ref)
    return expanded


def _row_evidence_bindings(repo_root: Path, row: dict[str, Any]) -> dict[str, Any]:
    bindings: dict[str, Any] = {}
    for field in ("source_evidence", "target_realization", "acceptance_trace"):
        value = row.get(field)
        if value is None:
            bindings[field] = []
            continue
        refs = _expand_refs(value)
        bindings[field] = [resolve_ref(repo_root, str(ref)) for ref in refs]
    return bindings


def _project_inline_rows(repo_root: Path, spec: dict[str, Any]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for movement in spec["movements"]:
        row = dict(movement)
        row["phase_partition"] = _phase_for_family(row["family"])
        row["locator_role"] = "evidence_ref_only"
        row["evidence_bindings"] = _row_evidence_bindings(repo_root, movement)
        rows.append(row)
    return rows


def _phase_for_family(family: str) -> str:
    if family in ("C1", "C8", "C9"):
        return "P1_ONLY_UNIMPLEMENTED"
    if family == "C2":
        return "P2_AND_P3"
    return "P3"


def _project_c7_rows(
    repo_root: Path,
    c7_matrix: dict[str, Any],
    design_rows: list[dict[str, str]],
    design_sha256: str,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    external = c7_matrix["movements"]
    if len(external) != 20 or len({row["movement_id"] for row in external}) != 20:
        raise ValueError("C7 matrix must contain 20 unique movement rows")
    design_ids = [row["movement_id"] for row in design_rows]
    matrix_ids = [row["movement_id"] for row in external]
    if design_ids != matrix_ids:
        raise ValueError("C7 design row identity/order drift vs matrix")
    if [row["disposition"] for row in design_rows] != [
        row["disposition"] for row in external
    ]:
        raise ValueError("C7 design disposition drift vs matrix")
    blockers = [
        row["movement_id"]
        for row in external
        if row["disposition"] == "UNASSIGNED_BLOCKER"
    ]
    if blockers:
        raise ValueError("C7 v3 matrix must contain zero UNASSIGNED_BLOCKER rows")
    rows: list[dict[str, Any]] = []
    for index, row in enumerate(external):
        projected = dict(row)
        projected["family"] = "C7"
        projected["phase_partition"] = "P1_ONLY_UNIMPLEMENTED"
        projected["p1_cell_scope"] = C7_SCOPE
        projected["locator_role"] = "evidence_ref_only"
        projected["evidence_bindings"] = _row_evidence_bindings(repo_root, row)
        source_marker = str(row["source_evidence"])
        exact_source_ref = (
            f"{C7_MATRIX_REL.as_posix()}#/movements/{index}/source_evidence"
        )
        exact_source_binding = resolve_ref(repo_root, exact_source_ref)
        if exact_source_binding["kind"] != "resolved":
            raise ValueError(
                f"C7 source evidence row binding failed: {row['movement_id']}"
            )
        exact_source_binding["legacy_marker"] = source_marker
        exact_source_binding["row_selector"] = row["movement_id"]
        projected["evidence_bindings"]["source_evidence"] = [exact_source_binding]
        rows.append(projected)
    binding = {
        "status": "EXACT_BOUND",
        "design_path": C7_DESIGN_REL.as_posix(),
        "design_sha256": design_sha256,
        "design_row_count": len(design_rows),
        "design_unassigned_blocker_count": len(blockers),
        "inventory_path": C7_INVENTORY_REL.as_posix(),
        "inventory_content_digest": C7_INVENTORY_DIGEST,
        "matrix_path": C7_MATRIX_REL.as_posix(),
        "matrix_content_digest": C7_MATRIX_DIGEST,
        "trace_path": C7_TRACE_REL.as_posix(),
        "trace_content_digest": C7_TRACE_DIGEST,
        "row_count": 20,
        "unassigned_blocker_count": len(blockers),
        "movement_ids_exact": True,
        "blocker_ids_exact": True,
        "row_contents_exact": True,
    }
    return rows, binding


