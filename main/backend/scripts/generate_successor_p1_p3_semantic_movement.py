def _disposition_counts(rows: list[dict[str, Any]]) -> dict[str, int]:
    counts = {disposition: 0 for disposition in sorted(ALLOWED_DISPOSITIONS)}
    for row in rows:
        counts[row["disposition"]] += 1
    return counts


def _family_partitions(rows: list[dict[str, Any]]) -> dict[str, Any]:
    partitions: dict[str, Any] = {}
    for family in FAMILIES:
        family_rows = [row for row in rows if row["family"] == family]
        partitions[family] = {
            "movement_count": len(family_rows),
            "unassigned_blocker_count": sum(
                row["disposition"] == "UNASSIGNED_BLOCKER" for row in family_rows
            ),
            "movement_ids": [row["movement_id"] for row in family_rows],
        }
        if family == "C7":
            partitions[family]["external_design_ref"] = C7_DESIGN_REL.as_posix()
    return partitions


